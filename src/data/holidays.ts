export function getAutomaticHolidayEntries(communityId?: string | null) {
  return communityId ? holidayCalendar2026[communityId] ?? [] : []
}

export function getAutomaticHolidayDates(communityId?: string | null) {
  return getAutomaticHolidayEntries(communityId).map((holiday) => holiday.date)
}

export function getHolidayName(dateKey: string, communityId?: string | null, localDates: string[] = []) {
  const officialHoliday = getAutomaticHolidayEntries(communityId).find((holiday) => holiday.date === dateKey)

  if (officialHoliday) {
    return officialHoliday.name
  }

  return localDates.includes(dateKey) ? 'Festivo local' : null
}
